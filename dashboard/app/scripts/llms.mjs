// The /llms.txt file (https://llmstxt.org): a short, plain description of the site and where its
// data lives, so language-model tools can use the dashboard's data without scraping the page.

/**
 * @param {{ title: string }} options
 * @returns {string}
 */
export function buildLlmsTxt({ title }) {
  return `# ${title}

> A dashboard of open source contributions: pull requests, issues, code reviews, commits and contribution score, by project and repository. It is a static page built from a report generated by opensource-contributions-tracker.

The page is interactive. The same data is published as plain JSON next to it.

## Data

- [activity.json](activity.json): every pull request and issue, one record per contributor and repository, with state, labels and dates.
- [contributions.json](contributions.json): commits, code reviews, contribution score and rank per contributor and repository.
- [meta.json](meta.json): when this site was built.

## Source

- [opensource-contributions-tracker](https://github.com/NihalJain/opensource-contributions-tracker): the report generator and this dashboard.
`;
}
